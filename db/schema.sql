-- Esquema relacional do prototipo de e-commerce (H2).
-- Mantenha este arquivo compativel com JdbcUserRepository e JdbcProductRepository.

-- Usuarios
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    username VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    cpf VARCHAR(11),
    role VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_users PRIMARY KEY (id)
);

-- Catalogo de produtos
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    stock INTEGER NOT NULL,
    image_data BLOB,
    image_type VARCHAR(20),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_products PRIMARY KEY (id)
);

-- Compatibilidade com bancos criados antes da inclusao das datas de cadastro.
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;

ALTER TABLE users ADD COLUMN IF NOT EXISTS cpf VARCHAR(11);
ALTER TABLE users ADD COLUMN IF NOT EXISTS role VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER';

ALTER TABLE products
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE products ADD COLUMN IF NOT EXISTS image_data BLOB;
ALTER TABLE products ADD COLUMN IF NOT EXISTS image_type VARCHAR(20);

-- Regras de integridade com nomes explicitos para facilitar manutencao.
ALTER TABLE users DROP CONSTRAINT IF EXISTS uq_users_username;

ALTER TABLE users
    ADD CONSTRAINT IF NOT EXISTS uq_users_email UNIQUE (email);

ALTER TABLE users
    ADD CONSTRAINT IF NOT EXISTS uq_users_cpf UNIQUE (cpf);

ALTER TABLE users
    ADD CONSTRAINT IF NOT EXISTS ck_users_role CHECK (role IN ('CUSTOMER', 'ADMIN'));

ALTER TABLE products
    ADD CONSTRAINT IF NOT EXISTS ck_products_price_nonnegative CHECK (price >= 0);

ALTER TABLE products
    ADD CONSTRAINT IF NOT EXISTS ck_products_stock_nonnegative CHECK (stock >= 0);

CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    total NUMERIC(12, 2) NOT NULL,
    payment_method VARCHAR(20) NOT NULL DEFAULT 'PIX',
    delivery_address VARCHAR(500) NOT NULL DEFAULT 'Endereco nao informado',
    status VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_orders PRIMARY KEY (id),
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT ck_orders_total CHECK (total >= 0),
    CONSTRAINT ck_orders_status CHECK (status IN ('CONFIRMED'))
);

ALTER TABLE orders ADD COLUMN IF NOT EXISTS payment_method VARCHAR(20) NOT NULL DEFAULT 'PIX';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS delivery_address VARCHAR(500) NOT NULL DEFAULT 'Endereco nao informado';
ALTER TABLE orders
    ADD CONSTRAINT IF NOT EXISTS ck_orders_payment_method CHECK (payment_method IN ('PIX', 'DINHEIRO', 'CARTAO'));

CREATE TABLE IF NOT EXISTS order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL,
    CONSTRAINT pk_order_items PRIMARY KEY (id),
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders(id),
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT uq_order_items_order_product UNIQUE (order_id, product_id),
    CONSTRAINT ck_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_items_price CHECK (unit_price >= 0)
);

CREATE INDEX IF NOT EXISTS idx_orders_user_created
    ON orders(user_id, created_at DESC);
